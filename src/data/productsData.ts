// QUICK QUERY AND FILTER HELPER FUNCTIONS
// ==========================================
export function getProductById(id: string): Product | undefined {
  return PRODUCTS_DATA.find(p => p.id === id);
}

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS_DATA.find(p => p.slug === slug);
}

export function getProductsByGroup(group: string): Product[] {
  if (group === 'all') return PRODUCTS_DATA;
  return PRODUCTS_DATA.filter(p => p.categoryGroup === group);
}

export function getProductsByCollection(collectionId: string): Product[] {
  return PRODUCTS_DATA.filter(p => p.collectionId === collectionId);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return PRODUCTS_DATA
    .filter(p => p.id !== product.id && (p.collectionId === product.collectionId || p.categoryGroup === product.categoryGroup))
    .slice(0, limit);
}
